#!/usr/bin/env node
/**
 * Emit the API surface as JSON, for consumers that cannot read the client
 * checkout — notably the space_code_agent in the backend repo, which needs the
 * name lists to check generated vibe code before it is deployed.
 *
 * The JSON is GENERATED, never authored. Regenerate it whenever the client's
 * ArrivalSpace surface or an @deprecated tag changes:
 *
 *   node tools/emit-api-surface.mjs [--out docs/api-surface.json] [path/to/arrival-api.js]
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readApiSurface, DEFAULT_RUNTIME } from "./api-surface.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));

const args = process.argv.slice(2);
const outIdx = args.indexOf("--out");
const outPath = outIdx !== -1 ? path.resolve(args[outIdx + 1]) : path.join(HERE, "../docs/api-surface.json");
const runtimeArg = args.filter((a, i) => a !== "--out" && i !== outIdx + 1)[0];

let surface;
try {
    surface = readApiSurface(runtimeArg ? path.resolve(runtimeArg) : DEFAULT_RUNTIME);
} catch (err) {
    console.error(err.message);
    process.exit(2);
}

const payload = {
    _comment: "GENERATED by tools/emit-api-surface.mjs — do not edit. Source of truth is the client's scripts/arrival-api.js.",
    generatedAt: new Date().toISOString().slice(0, 10),
    // Every function on ArrivalSpace. A call to anything not here throws.
    world: surface.world,
    // Every member on ArrivalScript, i.e. what `this.x` may legitimately be
    // (a vibe's own methods and params are additional and cannot be known here).
    instance: surface.instance,
    // Members that still work but have left the documented surface.
    // `replacement` is the ArrivalSpace name to use, or null when there is no
    // clean 1:1 and the advice has to be read.
    deprecated: surface.deprecated,
};

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, JSON.stringify(payload, null, 2) + "\n");

const dep = Object.entries(surface.deprecated);
console.log(`wrote ${path.relative(process.cwd(), outPath)}`);
console.log(`  world      : ${surface.world.length}`);
console.log(`  instance   : ${surface.instance.length}`);
console.log(`  deprecated : ${dep.length} (${dep.filter(([, v]) => v.replacement).length} with a 1:1 replacement)`);
